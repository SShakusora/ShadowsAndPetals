package com.sshakusora.shadowsandpetals.data.rockery.obj;

import java.nio.charset.StandardCharsets;
import java.util.Locale;

import static com.sshakusora.shadowsandpetals.data.rockery.obj.ObjModel.*;

/** Writes the normalized per-block OBJ representation used by NeoForge. */
public final class ObjModelWriter {
    public static final String MATERIAL_NAME = "rockery";
    public static final String MATERIAL_FILE_NAME = "material.mtl";
    public static final String TEXTURE_SLOT = "#texture";

    private ObjModelWriter() {
    }

    public static byte[] writeObj(ObjModelCutter.Part part) {
        StringBuilder output = new StringBuilder();
        output.append("# Generated by Shadows And Petals\n");
        output.append("mtllib ").append(MATERIAL_FILE_NAME).append('\n');
        if (!part.faces().isEmpty()) {
            output.append("o rockery\n");
            output.append("usemtl ").append(MATERIAL_NAME).append('\n');
        }

        int index = 1;
        for (ObjFace face : part.faces()) {
            ObjVector3 normal = normal(face);
            for (ObjVertex vertex : face.vertices()) {
                appendVector(output, "v", vertex.position());
            }
            for (ObjVertex vertex : face.vertices()) {
                ObjVector2 uv = vertex.uv() == null ? new ObjVector2(0.0D, 0.0D) : vertex.uv();
                output.append("vt ").append(number(uv.x())).append(' ').append(number(uv.y())).append('\n');
            }
            for (int i = 0; i < face.vertices().size(); i++) {
                appendVector(output, "vn", normal);
            }

            output.append('f');
            for (int i = 0; i < face.vertices().size(); i++) {
                int vertexIndex = index + i;
                output.append(' ').append(vertexIndex).append('/').append(vertexIndex).append('/').append(vertexIndex);
            }
            output.append('\n');
            index += face.vertices().size();
        }
        return output.toString().getBytes(StandardCharsets.UTF_8);
    }

    public static byte[] writeMtl() {
        return ("# Generated by Shadows And Petals\n"
                + "newmtl " + MATERIAL_NAME + "\n"
                + "Kd 1 1 1\n"
                + "map_Kd " + TEXTURE_SLOT + "\n")
                .getBytes(StandardCharsets.UTF_8);
    }

    private static ObjVector3 normal(ObjFace face) {
        ObjVector3 firstNormal = face.vertices().stream()
                .map(ObjVertex::normal)
                .filter(value -> value != null)
                .findFirst()
                .orElse(null);
        if (firstNormal != null) {
            return firstNormal.normalized();
        }

        ObjVector3 first = face.vertices().getFirst().position();
        ObjVector3 second = face.vertices().get(1).position();
        ObjVector3 third = face.vertices().get(2).position();
        return second.subtract(first).cross(third.subtract(first)).normalized();
    }

    private static void appendVector(StringBuilder output, String prefix, ObjVector3 vector) {
        output.append(prefix).append(' ')
                .append(number(vector.x())).append(' ')
                .append(number(vector.y())).append(' ')
                .append(number(vector.z())).append('\n');
    }

    private static String number(double value) {
        double normalized = Math.abs(value) < 1.0E-9D ? 0.0D : value;
        return String.format(Locale.ROOT, "%.8f", normalized)
                .replaceAll("0+$", "")
                .replaceAll("\\.$", "");
    }
}
